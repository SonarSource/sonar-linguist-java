package org.sonar.linguist;

import java.nio.charset.StandardCharsets;
import java.util.Arrays;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Stream;

final class GeneratedDetector {
  private static final String JAVA_EXTENSION = ".java";
  private static final Set<String> XCODE_EXTENSIONS = Set.of(".nib", ".xcworkspacedata", ".xcuserstate");
  private static final Set<String> PROTOBUF_EXTENSIONS =
    Set.of(".py", JAVA_EXTENSION, ".h", ".cc", ".cpp", ".m", ".rb", ".php");
  private static final Set<String> THRIFT_EXTENSIONS =
    Set.of(".rb", ".py", ".go", ".js", ".m", JAVA_EXTENSION, ".h", ".cc", ".cpp", ".php");
  private static final Set<String> HAXE_EXTENSIONS =
    Set.of(".js", ".py", ".lua", ".cpp", ".h", JAVA_EXTENSION, ".cs", ".php");
  private static final String PEG_JS_MARKER = "Generated by PEG.js";
  private static final String GO_VENDOR_PREFIX = "vendor/";
  private static final String GO_VENDOR_LABEL_CHARACTERS = "-0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz";
  private static final Set<String> GO_VENDOR_TOP_LEVEL_DOMAINS =
    Set.of("com", "edu", "gov", "in", "me", "net", "org", "fm", "io");
  private static final Pattern SOURCE_MAP_REFERENCE =
    Pattern.compile("^/[*/][#@] source(?:Mapping)?URL");
  private static final Pattern DART_GENERATED =
    Pattern.compile("generated code\\W{2,3}do not modify", Pattern.CASE_INSENSITIVE);
  private static final Pattern HTML_META = Pattern.compile("<meta(\\s++[^>]++)>", Pattern.CASE_INSENSITIVE);
  private static final Pattern HTML_ATTRIBUTE = Pattern.compile(
    "(?:^|\\s)(name|content|value)\\s*=\\s*(\"[^\"]+\"|'[^']+'|[^\\s\"']+)",
    Pattern.CASE_INSENSITIVE);
  private static final Pattern HTML_GENERATOR = Pattern.compile(
    "^(?:org\\s+mode|j?latex2html|groff|makeinfo|texi2html|ronn)\\b",
    Pattern.CASE_INSENSITIVE);
  private static final Pattern DOXYGEN =
    Pattern.compile("<!--\\s+Generated by Doxygen\\s+[.0-9]+\\s*-->", Pattern.CASE_INSENSITIVE);
  private static final Pattern POSTSCRIPT_DATA =
    Pattern.compile("^\\s*(?:currentfile eexec\\s+|/sfnts\\s+\\[\\s<)", Pattern.MULTILINE);
  private static final Pattern POSTSCRIPT_CREATOR = Pattern.compile(
    "\\d|draw|mpage|ImageMagick|inkscape|MATLAB|PCBNEW|pnmtops|\\(Unknown\\)|Serif Affinity|Filterimage -tops");
  private static final Pattern GIMP_SOURCE =
    Pattern.compile("^/\\* GIMP [a-zA-Z0-9\\- ]+ C-Source image dump \\(.+?\\.c\\) \\*/");
  private static final Pattern GIMP_HEADER =
    Pattern.compile("^/\\* {2}GIMP header image file format \\([a-zA-Z0-9\\- ]+\\): .+?\\.h {2}\\*/");

  private GeneratedDetector() {
  }

  static boolean detect(FileContent content) {
    return new Analysis(content).generated();
  }

  private static final class Analysis {
    private final String name;
    private final String extension;
    private final String data;
    private final List<String> lines;

    private Analysis(FileContent content) {
      name = content.path();
      extension = extension(name);
      data = new String(content.bytes(), StandardCharsets.ISO_8859_1);
      lines = data.isEmpty() ? List.of() : Arrays.asList(data.split("\\n", -1));
    }

    private boolean generated() {
      return xcodeFile()
        || matches("(?:^|/)\\.idea/")
        || matches("(^Pods|/Pods)/")
        || matches("(^|/)Carthage/Build/")
        || matches("__generated__/")
        || matches("\\.designer\\.(cs|vb)$", Pattern.CASE_INSENSITIVE)
        || matches("\\.feature\\.cs$", Pattern.CASE_INSENSITIVE)
        || matches("composer\\.lock")
        || matches("Cargo\\.lock")
        || matches("Cargo\\.toml\\.orig")
        || matches("deno\\.lock")
        || matches("(^|/)flake\\.lock$")
        || matches("(^|/)MODULE\\.bazel\\.lock$")
        || matches("node_modules/")
        || goVendor()
        || matches("(Gopkg|glide)\\.lock")
        || matches("Package\\.resolved")
        || matches("poetry\\.lock")
        || matches("pdm\\.lock")
        || matches("uv\\.lock")
        || matches("pixi\\.lock")
        || matches("(^|/)(\\w+\\.)?esy.lock$")
        || matches("npm-shrinkwrap\\.json")
        || matches("package-lock\\.json")
        || matches("pnpm-lock\\.yaml")
        || matches("(?:^|/)bun\\.lockb?$")
        || matches("(?:^|/)\\.terraform\\.lock\\.hcl$")
        || matches("(^|/)\\.pnp\\..*$")
        || matches("Godeps/")
        || matches(".\\.zep\\.(?:c|h|php)$")
        || matches("(?:^|/)htmlcov/")
        || minifiedFile()
        || hasSourceMap()
        || sourceMap()
        || compiledCoffeeScript()
        || generatedParser()
        || generatedNetDocfile()
        || generatedPostscript()
        || compiledCythonFile()
        || matches("Pipfile\\.lock")
        || matches("(?:^|/)gradlew(?:\\.bat)?$", Pattern.CASE_INSENSITIVE)
        || matches("(?:^|/)mvnw(?:\\.cmd)?$", Pattern.CASE_INSENSITIVE)
        || matches("(?:^|/)mise(?:\\.[^/]+)?\\.lock$")
        || matches("(?:^|/)\\.secrets\\.baseline$")
        || matches("(?:^|/)(Julia)?Manifest(-v\\d+\\.\\d+)?\\.toml$")
        || generatedGo()
        || generatedProtocolBufferFromGo()
        || generatedProtocolBuffer()
        || generatedJavaScriptProtocolBuffer()
        || generatedTypeScriptProtocolBuffer()
        || generatedTwirpRuby()
        || generatedApacheThrift()
        || generatedJniHeader()
        || vcrCassette()
        || generatedAntlr()
        || generatedModule()
        || generatedUnity3dMeta()
        || generatedRacc()
        || generatedJflex()
        || generatedGrammarKit()
        || generatedRoxygen2()
        || generatedHtml()
        || generatedJison()
        || generatedGrpcCpp()
        || generatedDart()
        || generatedPerlPpportHeader()
        || generatedGameMakerStudio()
        || generatedGimp()
        || generatedVisualStudio6()
        || generatedHaxe()
        || generatedJooq()
        || matches("_tlb\\.pas$", Pattern.CASE_INSENSITIVE)
        || generatedSorbetRbi()
        || generatedMysqlViewDefinitionFormat()
        || matches("(?:^|/)\\.sqlx/query-[a-f\\d]{64}\\.json$");
    }

    private boolean xcodeFile() {
      return XCODE_EXTENSIONS.contains(extension);
    }

    private boolean maybeMinified() {
      return extension.equalsIgnoreCase(".js") || extension.equalsIgnoreCase(".css");
    }

    private boolean minifiedFile() {
      if (!maybeMinified() || lines.isEmpty()) {
        return false;
      }
      long characters = lines.stream().mapToLong(String::length).sum();
      return characters / lines.size() > 110;
    }

    private boolean hasSourceMap() {
      return maybeMinified() && lastLines(2).stream()
        .anyMatch(line -> SOURCE_MAP_REFERENCE.matcher(line).find() || line.contains("sourceURL="));
    }

    private boolean sourceMap() {
      if (!extension.equalsIgnoreCase(".map")) {
        return false;
      }
      String first = line(0);
      return Pattern.compile("(\\.css|\\.js)\\.map$", Pattern.CASE_INSENSITIVE).matcher(name).find()
        || first.matches("^\\{\"version\":\\d+,.*")
        || first.startsWith("/** Begin line maps. **/{");
    }

    private boolean compiledCoffeeScript() {
      if (!extension.equals(".js") || lines.isEmpty()) {
        return false;
      }
      if (line(0).startsWith("// Generated by ")) {
        return true;
      }
      if (lines.size() < 2 || !line(0).equals("(function() {")
        || !line(lines.size() - 2).equals("}).call(this);") || !line(lines.size() - 1).isEmpty()) {
        return false;
      }
      int score = 0;
      Pattern temporary = Pattern.compile("(_fn|_i|_len|_ref|_results)");
      Pattern helper = Pattern.compile("(__bind|__extends|__hasProp|__indexOf|__slice)");
      for (String line : lines) {
        if (line.contains("var ")) {
          score += count(temporary, line) + 3 * count(helper, line);
        }
      }
      return score >= 3;
    }

    private boolean generatedNetDocfile() {
      return extension.equalsIgnoreCase(".xml") && lines.size() > 3
        && line(1).contains("<doc>") && line(2).contains("<assembly>")
        && line(lines.size() - 2).contains("</doc>");
    }

    private boolean generatedParser() {
      if (!extension.equals(".js")) {
        return false;
      }
      return firstBlockCommentBody(String.join("", firstLines(5))).contains(PEG_JS_MARKER);
    }

    /**
     * Upstream Linguist looks for the PEG.js marker with a regex that walks the file up to the first
     * block comment and then through that comment. Java compiles its two alternation loops into
     * recursive matcher nodes that use six stack frames per character, so first lines a few thousand
     * characters long overflow the stack. Locating the comment delimiters directly is equivalent and
     * linear.
     */
    private static String firstBlockCommentBody(String beginning) {
      int start = beginning.indexOf("/*");
      if (start < 0) {
        return "";
      }
      int bodyStart = start + 2;
      int end = beginning.indexOf("*/", bodyStart);
      return end < 0 ? beginning.substring(bodyStart) : beginning.substring(bodyStart, end);
    }

    private boolean generatedPostscript() {
      if (!Set.of(".ps", ".eps", ".pfa").contains(extension)) {
        return false;
      }
      if (POSTSCRIPT_DATA.matcher(data).find()) {
        return true;
      }
      String creator = firstLines(10).stream().filter(line -> line.startsWith("%%Creator: ")).findFirst().orElse(null);
      if (creator == null) {
        return false;
      }
      if (POSTSCRIPT_CREATOR.matcher(creator).find()) {
        return true;
      }
      return creator.contains("EAGLE")
        && firstLines(5).stream().anyMatch(line -> line.startsWith("%%Title: EAGLE Drawing "));
    }

    private boolean generatedGo() {
      return extension.equals(".go") && lines.size() > 1
        && firstLines(40).stream().anyMatch(line -> line.startsWith("// Code generated "));
    }

    private boolean generatedProtocolBufferFromGo() {
      return extension.equals(".proto") && lines.size() > 1
        && firstLines(20).stream().anyMatch(line -> line.contains("This file was autogenerated by go-to-protobuf"));
    }

    private boolean generatedProtocolBuffer() {
      return PROTOBUF_EXTENSIONS.contains(extension) && lines.size() > 1
        && firstLines(3).stream()
          .anyMatch(line -> line.contains("Generated by the protocol buffer compiler.  DO NOT EDIT!"));
    }

    private boolean generatedJavaScriptProtocolBuffer() {
      return extension.equals(".js") && lines.size() > 6 && line(5).contains("GENERATED CODE -- DO NOT EDIT!");
    }

    private boolean generatedTypeScriptProtocolBuffer() {
      return extension.equals(".ts") && lines.size() > 4
        && line(0).contains("Code generated by protoc-gen-ts_proto. DO NOT EDIT.");
    }

    private boolean generatedTwirpRuby() {
      return extension.equals(".rb") && lines.size() > 1 && firstLines(3).stream()
        .anyMatch(line -> line.contains("Code generated by protoc-gen-twirp_ruby") && line.contains("DO NOT EDIT."));
    }

    private boolean generatedApacheThrift() {
      return THRIFT_EXTENSIONS.contains(extension)
        && firstLines(6).stream().anyMatch(line -> line.contains("Autogenerated by Thrift Compiler"));
    }

    private boolean generatedJniHeader() {
      return extension.equals(".h") && lines.size() > 2
        && line(0).contains("/* DO NOT EDIT THIS FILE - it is machine generated */")
        && line(1).contains("#include <jni.h>");
    }

    private boolean vcrCassette() {
      return extension.equals(".yml") && lines.size() > 2
        && line(lines.size() - 2).contains("recorded_with: VCR");
    }

    private boolean generatedAntlr() {
      return extension.equals(".g") && lines.size() > 2 && line(1).contains("generated by Xtest");
    }

    private boolean compiledCythonFile() {
      return Set.of(".c", ".cpp").contains(extension) && lines.size() > 1
        && line(0).contains("Generated by Cython");
    }

    private boolean generatedModule() {
      return extension.equals(".mod") && lines.size() > 1
        && (line(0).contains("PCBNEW-LibModule-V") || line(0).contains("GFORTRAN module version '"));
    }

    private boolean generatedUnity3dMeta() {
      return extension.equals(".meta") && lines.size() > 1 && line(0).contains("fileFormatVersion: ");
    }

    private boolean generatedRacc() {
      return extension.equals(".rb") && lines.size() > 2
        && line(2).startsWith("# This file is automatically generated by Racc");
    }

    private boolean generatedJflex() {
      return extension.equals(JAVA_EXTENSION) && lines.size() > 1
        && line(0).startsWith("/* The following code was generated by JFlex ");
    }

    private boolean generatedGrammarKit() {
      return extension.equals(JAVA_EXTENSION) && lines.size() > 1
        && line(0).startsWith("// This is a generated file. Not intended for manual editing.");
    }

    private boolean generatedRoxygen2() {
      return extension.equals(".Rd") && lines.size() > 1
        && line(0).contains("% Generated by roxygen2: do not edit by hand");
    }

    private boolean generatedJison() {
      return extension.equals(".js") && lines.size() > 1
        && (line(0).startsWith("/* parser generated by jison ") || line(0).startsWith("/* generated by jison-lex "));
    }

    private boolean generatedGrpcCpp() {
      return Set.of(".cpp", ".hpp", ".h", ".cc").contains(extension) && lines.size() > 1
        && line(0).startsWith("// Generated by the gRPC");
    }

    private boolean generatedDart() {
      return extension.equals(".dart") && lines.size() > 1
        && firstLines(3).stream().anyMatch(line -> DART_GENERATED.matcher(line).find());
    }

    private boolean generatedPerlPpportHeader() {
      return name.endsWith("ppport.h") && lines.size() > 10
        && line(8).contains("Automatically created by Devel::PPPort");
    }

    private boolean generatedGameMakerStudio() {
      if (!Set.of(".yy", ".yyp").contains(extension) || lines.size() <= 3) {
        return false;
      }
      return Pattern.compile("^\\s*[\\[{]").matcher(String.join("", firstLines(3))).find()
        || Pattern.compile("^\\d\\.\\d\\.\\d.+\\|\\{").matcher(line(0)).find();
    }

    private boolean generatedGimp() {
      if (!Set.of(".c", ".h").contains(extension) || lines.isEmpty()) {
        return false;
      }
      return GIMP_SOURCE.matcher(line(0)).find() || GIMP_HEADER.matcher(line(0)).find();
    }

    private boolean generatedVisualStudio6() {
      return extension.equalsIgnoreCase(".dsp") && firstLines(3).stream()
        .anyMatch(line -> line.contains("# Microsoft Developer Studio Generated Build File"));
    }

    private boolean generatedHaxe() {
      return HAXE_EXTENSIONS.contains(extension)
        && firstLines(3).stream().anyMatch(line -> line.contains("Generated by Haxe"));
    }

    private boolean generatedHtml() {
      if (!Set.of(".html", ".htm", ".xhtml").contains(extension.toLowerCase(Locale.ROOT))
        || lines.size() <= 1) {
        return false;
      }
      if (firstLines(2).stream()
        .anyMatch(line -> line.contains("<!-- Generated by pkgdown: do not edit by hand -->"))) {
        return true;
      }
      if (lines.size() > 2 && line(2).startsWith("<!-- This is an automatically generated file.")) {
        return true;
      }
      if (firstLines(31).stream().anyMatch(line -> DOXYGEN.matcher(line).find())) {
        return true;
      }
      Matcher matcher = HTML_META.matcher(String.join(" ", firstLines(31)));
      while (matcher.find()) {
        Map<String, String> attributes = htmlAttributes(matcher.group(1));
        if ("generator".equalsIgnoreCase(attributes.get("name"))
          && Stream.of(attributes.get("content"), attributes.get("value"))
            .filter(java.util.Objects::nonNull)
            .anyMatch(value -> HTML_GENERATOR.matcher(value).find())) {
          return true;
        }
      }
      return false;
    }

    private boolean generatedJooq() {
      return extension.equalsIgnoreCase(JAVA_EXTENSION)
        && firstLines(2).stream().anyMatch(line -> line.contains("This file is generated by jOOQ."));
    }

    private boolean generatedSorbetRbi() {
      return extension.equalsIgnoreCase(".rbi") && lines.size() >= 5
        && line(0).matches("^# typed:.*")
        && line(2).contains("DO NOT EDIT MANUALLY")
        && line(4).matches("^# Please (run|instead update this file by running) `bin/tapioca.*");
    }

    private boolean generatedMysqlViewDefinitionFormat() {
      return extension.equalsIgnoreCase(".frm") && line(0).contains("TYPE=VIEW");
    }

    private boolean goVendor() {
      int vendorStart = name.indexOf(GO_VENDOR_PREFIX);
      while (vendorStart >= 0) {
        int domainStart = vendorStart + GO_VENDOR_PREFIX.length();
        int domainEnd = name.indexOf('/', domainStart);
        if (domainEnd > domainStart && isGoVendorDomain(name.substring(domainStart, domainEnd))) {
          return true;
        }
        vendorStart = name.indexOf(GO_VENDOR_PREFIX, domainStart);
      }
      return false;
    }

    private static boolean isGoVendorDomain(String domain) {
      String[] labels = domain.split("\\.", -1);
      if (labels.length < 2 || !GO_VENDOR_TOP_LEVEL_DOMAINS.contains(labels[labels.length - 1])) {
        return false;
      }
      for (int index = 0; index < labels.length - 1; index++) {
        if (!isGoVendorLabel(labels[index])) {
          return false;
        }
      }
      return true;
    }

    private static boolean isGoVendorLabel(String label) {
      if (label.isEmpty() || label.charAt(0) == '-' || label.charAt(label.length() - 1) == '-') {
        return false;
      }
      return label.chars().allMatch(character -> GO_VENDOR_LABEL_CHARACTERS.indexOf(character) >= 0);
    }

    private static String extension(String path) {
      String filename = path.substring(path.lastIndexOf('/') + 1);
      int dot = filename.lastIndexOf('.');
      return dot <= 0 ? "" : filename.substring(dot);
    }

    private static int count(Pattern pattern, String value) {
      int matches = 0;
      Matcher matcher = pattern.matcher(value);
      while (matcher.find()) {
        matches++;
      }
      return matches;
    }

    private static Map<String, String> htmlAttributes(String source) {
      Matcher matcher = HTML_ATTRIBUTE.matcher(source);
      java.util.LinkedHashMap<String, String> attributes = new java.util.LinkedHashMap<>();
      while (matcher.find()) {
        String value = matcher.group(2);
        if ((value.startsWith("\"") && value.endsWith("\"")) || (value.startsWith("'") && value.endsWith("'"))) {
          value = value.substring(1, value.length() - 1);
        }
        attributes.put(matcher.group(1).toLowerCase(Locale.ROOT), value);
      }
      return attributes;
    }

    private boolean matches(String regex) {
      return matches(regex, 0);
    }

    private boolean matches(String regex, int flags) {
      return Pattern.compile(regex, flags).matcher(name).find();
    }

    private String line(int index) {
      return index >= 0 && index < lines.size() ? lines.get(index) : "";
    }

    private List<String> firstLines(int count) {
      return lines.subList(0, Math.min(count, lines.size()));
    }

    private List<String> lastLines(int count) {
      return lines.subList(Math.max(0, lines.size() - count), lines.size());
    }
  }

}
