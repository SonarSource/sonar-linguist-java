  @TempDir
  Path temporary;
  private final Linguist linguist = Linguist.create();

  @Test
  void countsBytesNotFilesAndExcludesIneligibleFiles() throws Exception {
    Path root = temporary.resolve("repo");
    try (Git git = Git.init().setDirectory(root.toFile()).call()) {
      write(root, "src/A.java", "a".repeat(60));
      write(root, "src/B.java", "b".repeat(20));
      write(root, "web/app.js", "c".repeat(20));
      write(root, "docs/Example.java", "d".repeat(90));
      write(root, "node_modules/lib/index.js", "e".repeat(90));
      write(root, "build/generated/A.java",
        "// Generated by the protocol buffer compiler.  DO NOT EDIT!\n" + "f".repeat(90));
      write(root, "app.min.js", "g".repeat(111));
      write(root, "schema.sql", "select 1;");
      write(root, "readme.md", "prose");
      write(root, "data.unknown", "unknown");
      Files.write(root.resolve("binary.java"), new byte[] {1, 0, 2});
      RevCommit commit = commit(git);
      write(root, "src/A.java", "uncommitted contents");
      write(root, "untracked.js", "untracked contents");
      RepositoryAnalysis result = linguist.analyzeRepository(root);
      assertThat(result.commitId()).isEqualTo(commit.name());
      assertThat(result.totalBytes()).isEqualTo(100);
      assertThat(stats(result, "Java")).isEqualTo(new LanguageStats(80, 80));
      assertThat(stats(result, "JavaScript")).isEqualTo(new LanguageStats(20, 20));
      assertThat(result.includedFiles()).hasSize(3);
      assertThat(result.includedFiles().get("src/A.java").name()).isEqualTo("Java");
      Map<String, Language> includedFiles = result.includedFiles();
      Map<Language, LanguageStats> languages = result.languages();
      assertThatThrownBy(includedFiles::clear).isInstanceOf(UnsupportedOperationException.class);
      assertThatThrownBy(languages::clear).isInstanceOf(UnsupportedOperationException.class);
    }
  }

  @Test
  void supportsAttributeOverridesNestedPrecedenceAndAliases() throws Exception {
    Path root = temporary.resolve("repo");
    try (Git git = Git.init().setDirectory(root.toFile()).call()) {
      write(root, ".gitattributes", """
          *.sql linguist-detectable
          special.unknown linguist-language=cpp
          node_modules/** -linguist-vendored linguist-generated=false
          generated.java linguist-generated
          restored.min.js linguist-generated=false linguist-vendored=false
          docs/** -linguist-documentation
          hidden.java -linguist-detectable
          excluded.java linguist-detectable=false
          disabled.java linguist-vendored=true
          *.txt linguist-language=Java
          nested/** linguist-language=JavaScript
          mystery.java linguist-language=not-a-language
          binary.java linguist-language=Java linguist-detectable
          """);
      write(root, "nested/.gitattributes", "*.txt linguist-language=Python\n");
      Map<String, String> expected = Map.of(
          "schema.sql", "SQL", "special.unknown", "C++",
          "node_modules/lib.js", "JavaScript", "restored.min.js", "JavaScript",
          "docs/Example.java", "Java", "plain.txt", "Java", "nested/file.txt", "Python");
      for (String path : expected.keySet()) {
        write(root, path, "x".repeat(10));
      }
      for (String path : new String[] {
        "generated.java", "hidden.java", "excluded.java", "disabled.java", "mystery.java"
      }) {
        write(root, path, "x".repeat(10));
      }
      Files.write(root.resolve("binary.java"), new byte[] {1, 0, 2});
      commit(git);
      // Host-local and working tree attributes must never change the result.
      write(root, ".git/info/attributes", "* linguist-generated\n");
      Path globalAttributes = temporary.resolve("global-attributes");
      Files.writeString(globalAttributes, "* linguist-generated\n");
      git.getRepository().getConfig().setString("core", null, "attributesFile", globalAttributes.toString());
      git.getRepository().getConfig().save();
      write(root, ".gitattributes", "* linguist-generated\n");
      RepositoryAnalysis result = linguist.analyzeRepository(root);
      assertThat(result.totalBytes()).isEqualTo(70);
      assertThat(result.includedFiles()).containsOnlyKeys(expected.keySet());
      expected.forEach((path, language) -> assertThat(result.includedFiles().get(path).name()).isEqualTo(language));
    }
  }

  @Test
  void attributesComeFromSelectedRevisionAndUnspecifiedRestoresDefaults() throws Exception {
    Path root = temporary.resolve("repo");
    try (Git git = Git.init().setDirectory(root.toFile()).call()) {
      write(root, "schema.sql", "s".repeat(10));
      write(root, "main.java", "j".repeat(20));
      write(root, ".gitattributes", """
        *.sql linguist-detectable
        *.java linguist-language=Python
        main.java !linguist-language
        """);
      RevCommit old = commit(git);
      git.tag().setName("v1").setObjectId(old).setSigned(false)
          .setTagger(new PersonIdent("Test", "test@example.com")).call();
      write(root, ".gitattributes", "*.java linguist-language=Ruby\n");
      RevCommit latest = commit(git);
      assertThat(linguist.analyzeRepository(root, old.name()).totalBytes()).isEqualTo(30);
      assertThat(linguist.analyzeRepository(root, "v1").totalBytes()).isEqualTo(30);
      assertThat(linguist.analyzeRepository(root).totalBytes()).isEqualTo(20);
      assertThat(linguist.analyzeRepository(root).includedFiles().get("main.java").name()).isEqualTo("Ruby");
      assertThat(linguist.analyzeRepository(root).commitId()).isEqualTo(latest.name());
      assertThat(linguist.analyzeRepository(root, "v1").includedFiles().get("main.java").name()).isEqualTo("Java");
    }
  }

  @Test
  void groupsLanguagesAndCountsFullSizesDespiteBoundedReads() throws Exception {
    Path root = temporary.resolve("repo");
    try (Git git = Git.init().setDirectory(root.toFile()).call()) {
      write(root, "app.tsx", "t".repeat(100_000));
      write(root, "main.ts", "t".repeat(50_000));
      commit(git);
      RepositoryAnalysis result = linguist.analyzeRepository(root);
      assertThat(result.totalBytes()).isEqualTo(150_000);
      assertThat(result.languages()).hasSize(1);
      assertThat(stats(result, "TypeScript")).isEqualTo(new LanguageStats(150_000, 100));
      assertThat(result.includedFiles().get("app.tsx").name()).isEqualTo("TypeScript");
    }
  }

  @Test
  void limitsDetectionTo128KiBButCountsTheFullBlobSize() throws Exception {
    Path root = temporary.resolve("repo");
    try (Git git = Git.init().setDirectory(root.toFile()).call()) {
      String content = "a".repeat(128 * 1024) + "\nrecorded_with: VCR\n";
      write(root, ".gitattributes", "fixture.yml linguist-detectable\n");
      write(root, "fixture.yml", content);
      commit(git);

      RepositoryAnalysis result = linguist.analyzeRepository(root);

      assertThat(result.totalBytes()).isEqualTo(content.getBytes(StandardCharsets.UTF_8).length);
      assertThat(result.includedFiles()).containsOnlyKeys("fixture.yml");
      assertThat(result.includedFiles().get("fixture.yml").name()).isEqualTo("YAML");
    }
  }

  @Test
  void excludesLfsPointersOnlyWhenCommittedAttributesTrackThem() throws Exception {
    Path root = temporary.resolve("repo");
    String pointer = """
      version https://git-lfs.github.com/spec/v1
      oid sha256:a9d8db4a33528bbd0ff5f88fcbd0ddf74ee5dc150b4e02e77e0ee4f4002a1eb9
      size 14131452
      """;
    String source = "puts 'Hello'\n";
    try (Git git = Git.init().setDirectory(root.toFile()).call()) {
      write(root, "tracked.rb", pointer);
      write(root, "source.rb", source);
      write(root, "plain.py", pointer);
      write(root, "nested/included.rb", pointer);
      git.add().addFilepattern(".").call();
      write(root, ".gitattributes", "*.rb filter=lfs\n");
      write(root, "nested/.gitattributes", "included.rb -filter\n");
      git.add().addFilepattern(".gitattributes").addFilepattern("nested/.gitattributes").call();
      commitStaged(git);

      write(root, ".gitattributes", "*.rb -filter\nplain.py filter=lfs\n");
      RepositoryAnalysis result = linguist.analyzeRepository(root);

      assertThat(result.totalBytes()).isEqualTo(2L * pointer.getBytes(StandardCharsets.UTF_8).length
        + source.getBytes(StandardCharsets.UTF_8).length);
      assertThat(result.includedFiles()).containsOnlyKeys("source.rb", "plain.py", "nested/included.rb");
      assertThat(stats(result, "Ruby").bytes()).isEqualTo(pointer.getBytes(StandardCharsets.UTF_8).length
        + source.getBytes(StandardCharsets.UTF_8).length);
      assertThat(stats(result, "Python").bytes()).isEqualTo(pointer.getBytes(StandardCharsets.UTF_8).length);
    }
  }

  @Test
  void customCatalogControlsAttributesTypesAndGroups() throws Exception {
    int javaId = linguist.detect("Main.java", new byte[] {(byte) 'x'}).language().orElseThrow().languageId();
    String yaml = """
        Java:
          language_id: %d
          type: data
          extensions: [.java]
          aliases: [custom-java]
        Example:
          language_id: -1
          type: programming
          extensions: [.example]
          group: Java
        """.formatted(javaId);
    Linguist custom = Linguist.create(new ByteArrayInputStream(yaml.getBytes(StandardCharsets.UTF_8)));
    Path root = temporary.resolve("repo");
    try (Git git = Git.init().setDirectory(root.toFile()).call()) {
      write(root, "excluded.java", "x".repeat(40));
      write(root, "included.java", "j".repeat(10));
      write(root, "file.example", "e".repeat(20));
      write(root, "alias.unknown", "a".repeat(30));
      write(root, ".gitattributes", """
          included.java linguist-detectable
          alias.unknown linguist-language=custom-java linguist-detectable
          """);
      commit(git);
      RepositoryAnalysis result = custom.analyzeRepository(root);
      assertThat(result.totalBytes()).isEqualTo(60);
      assertThat(result.includedFiles()).containsOnlyKeys("included.java", "file.example", "alias.unknown");
      assertThat(result.languages()).containsExactly(Map.entry(
          new Language(javaId, "Java", LanguageType.DATA), new LanguageStats(60, 100)));
    }
  }

  @Test
  void supportsBareRepositoriesAndSkipsSymlinksAndSubmodules() throws Exception {
    Path root = temporary.resolve("repo");
    try (Git git = Git.init().setDirectory(root.toFile()).call()) {
      write(root, "main.java", "j".repeat(10));
      RevCommit first = commit(git);
      Files.createSymbolicLink(root.resolve("linked.java"), Path.of("main.java"));
      git.add().addFilepattern(".").call();
      DirCache index = git.getRepository().lockDirCache();
      try {
        var builder = index.builder();
        builder.keep(0, index.getEntryCount());
        DirCacheEntry submodule = new DirCacheEntry("module.java");
        submodule.setFileMode(FileMode.GITLINK);
        submodule.setObjectId(first);
        builder.add(submodule);
        assertThat(builder.commit()).isTrue();
      } finally {
        index.unlock();
      }
      git.commit().setSign(false).setMessage("Add links")
        .setAuthor("Test", "test@example.com")
        .setCommitter("Test", "test@example.com").call();
      Path bare = temporary.resolve("bare.git");
      try (Git ignored = Git.cloneRepository().setURI(root.toUri().toString())
          .setBare(true).setDirectory(bare.toFile()).call()) {
        RepositoryAnalysis result = linguist.analyzeRepository(bare);
        assertThat(result.totalBytes()).isEqualTo(10);
        assertThat(result.includedFiles()).containsOnlyKeys("main.java");
      }
    }
  }

  @Test
  void handlesEmptyRepositoriesAndExcludesEmptyFiles() throws Exception {
    Path root = temporary.resolve("repo");
    try (Git git = Git.init().setDirectory(root.toFile()).call()) {
      RepositoryAnalysis empty = linguist.analyzeRepository(root);
      assertThat(empty.commitId()).isEmpty();
      assertThat(empty.totalBytes()).isZero();
      assertThat(empty.languages()).isEmpty();
      write(root, "empty.java", "");
      RevCommit commit = commit(git);
      RepositoryAnalysis zero = linguist.analyzeRepository(root);
      assertThat(zero.commitId()).isEqualTo(commit.name());
      assertThat(zero.totalBytes()).isZero();
      assertThat(zero.languages()).isEmpty();
      assertThat(zero.includedFiles()).isEmpty();
      write(root, "empty.java", "data");
      write(root, ".gitattributes", "* linguist-generated\n");
      commit(git);
      assertThat(linguist.analyzeRepository(root).languages()).isEmpty();
    }
  }

  @Test
  void stopsAnalysisWhenTreeSizeReachesLimit() throws Exception {
    Path root = temporary.resolve("repo");
    try (Git git = Git.init().setDirectory(root.toFile()).call()) {
      write(root, "a.java", "a".repeat(10));
      write(root, "b.java", "b".repeat(10));
      RevCommit belowLimit = commit(git);
      RepositoryAnalyzer analyzer = new RepositoryAnalyzer(linguist, LanguageCatalog.bundled(), 3);
      assertThat(analyzer.analyze(root, belowLimit.name()).totalBytes()).isEqualTo(20);

      write(root, "c.java", "c".repeat(10));
      RevCommit atLimit = commit(git);
      RepositoryAnalysis result = analyzer.analyze(root, atLimit.name());
      assertThat(result.commitId()).isEqualTo(atLimit.name());
      assertThat(result.totalBytes()).isZero();
      assertThat(result.languages()).isEmpty();
      assertThat(result.includedFiles()).isEmpty();
    }
  }

  @Test
  void boundsTraversalOfPathologicalTrees() throws Exception {
    Path root = temporary.resolve("repo");
    try (Git git = Git.init().setDirectory(root.toFile()).call();
      var inserter = git.getRepository().newObjectInserter()) {
      ObjectId treeId = inserter.insert(new TreeFormatter());
      for (int depth = 0; depth < 32; depth++) {
        TreeFormatter tree = new TreeFormatter();
        tree.append("entry0", FileMode.TREE, treeId);
        tree.append("entry1", FileMode.TREE, treeId);
        treeId = inserter.insert(tree);
      }
      inserter.flush();
      try (RevWalk walk = new RevWalk(git.getRepository())) {
        assertThat(RepositoryAnalyzer.treeSize(git.getRepository(), walk.parseTree(treeId), 500)).isEqualTo(500);
      }
    }
  }

  @Test
  void failsClearlyForInvalidInputs() throws Exception {
    assertThatThrownBy(() -> linguist.analyzeRepository(temporary)).isInstanceOf(IllegalArgumentException.class);
    assertThatThrownBy(() -> linguist.analyzeRepository(temporary, " ")).isInstanceOf(IllegalArgumentException.class);
    Path root = temporary.resolve("repo");
    try (Git git = Git.init().setDirectory(root.toFile()).call()) {
      write(root, "main.java", "text");
      commit(git);
      assertThatThrownBy(() -> linguist.analyzeRepository(root, "does-not-exist"))
        .isInstanceOf(IllegalArgumentException.class);
    }
  }

  @Test
  void instanceSupportsConcurrentRepositoryAnalysis() throws Exception {
    Path root = temporary.resolve("repo");
    try (Git git = Git.init().setDirectory(root.toFile()).call()) {
      write(root, "main.java", "j".repeat(40));
      commit(git);
      try (var executor = Executors.newVirtualThreadPerTaskExecutor()) {
        var first = executor.submit(() -> linguist.analyzeRepository(root));
        var second = executor.submit(() -> linguist.analyzeRepository(root));
        assertThat(second.get()).isEqualTo(first.get());
      }
    }
  }

  private static void write(Path root, String name, String content) throws Exception {
    Path target = root.resolve(name);
    Files.createDirectories(target.getParent());
    Files.writeString(target, content, StandardCharsets.UTF_8);
  }

  private static RevCommit commit(Git git) throws Exception {
    git.add().addFilepattern(".").call();
    return commitStaged(git);
  }

  private static RevCommit commitStaged(Git git) throws Exception {
    return git.commit().setSign(false).setMessage("Fixture")
      .setAuthor("Test", "test@example.com")
      .setCommitter("Test", "test@example.com").call();
  }

  private static LanguageStats stats(RepositoryAnalysis result, String name) {
    return result.languages().entrySet().stream()
        .filter(entry -> entry.getKey().name().equals(name))
        .map(Map.Entry::getValue).findFirst().orElseThrow();
  }
